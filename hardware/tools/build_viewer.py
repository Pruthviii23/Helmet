"""
Turn the Blender output into the viewer's assets.

  python hardware/tools/build_viewer.py

Reads  hardware/renders/helmet/viewer_build/{raw/*.png, stills/*.png, hotspots.json}
       hardware/renders/helmet/helmate_on_helmet_info.json
Writes hardware/viewer/{frames/*.jpg, stills/*.jpg, data.js}
"""
import json, os, glob
from PIL import Image

HW = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(HW, "renders", "helmet", "viewer_build")
DST = os.path.join(HW, "viewer")
BG = (14, 16, 20)   # must match --stage-bg in the HTML


def flatten(src, dst, quality, size=None):
    im = Image.open(src).convert("RGBA")
    if size:
        im = im.resize(size, Image.LANCZOS)
    bg = Image.new("RGBA", im.size, BG + (255,))
    bg.alpha_composite(im)
    bg.convert("RGB").save(dst, "JPEG", quality=quality, optimize=True, progressive=True)


os.makedirs(os.path.join(DST, "frames"), exist_ok=True)
os.makedirs(os.path.join(DST, "stills"), exist_ok=True)

n = 0
for f in sorted(glob.glob(os.path.join(SRC, "raw", "*.png"))):
    out = os.path.join(DST, "frames", os.path.basename(f)[:-4] + ".jpg")
    if not os.path.exists(out) or os.path.getmtime(out) < os.path.getmtime(f):
        flatten(f, out, 84)
        n += 1
s = 0
for f in sorted(glob.glob(os.path.join(SRC, "stills", "*.png"))):
    out = os.path.join(DST, "stills", os.path.basename(f)[:-4] + ".jpg")
    flatten(f, out, 88)
    s += 1

hs = json.load(open(os.path.join(SRC, "hotspots.json")))
info = json.load(open(os.path.join(HW, "renders", "helmet", "helmate_on_helmet_info.json")))
data = {
    "azStep": hs["az_step"], "els": hs["els"], "res": hs["res"],
    "frames": hs["frames"], "cableCm": info["cable_length_cm"],
    "variants": sorted({os.path.basename(f).split("_e")[0] for f in glob.glob(os.path.join(DST, "frames", "*.jpg"))}),
    "stills": sorted(os.path.basename(f)[:-4] for f in glob.glob(os.path.join(DST, "stills", "*.jpg"))),
}
with open(os.path.join(DST, "data.js"), "w", encoding="utf-8") as fh:
    fh.write("// generated by hardware/tools/build_viewer.py\nwindow.HELMATE_DATA = ")
    json.dump(data, fh, separators=(",", ":"))
    fh.write(";\n")
mb = sum(os.path.getsize(f) for f in glob.glob(os.path.join(DST, "*", "*.jpg"))) / 1e6
print(f"frames converted: {n}, stills: {s}, total images {mb:.1f} MB, variants {data['variants']}")

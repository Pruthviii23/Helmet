"""
Turn the Blender output into the viewer's assets.

  python hardware/tools/build_viewer.py

Reads  hardware/renders/helmet/viewer_build_hd/{raw/*.png, hotspots.json}   (2400x1800 turntable)
       hardware/renders/helmet/viewer_build/stills/*.png                    (close-ups)
       hardware/renders/helmet/helmate_on_helmet_info.json                  (cable lengths)
Writes hardware/viewer/frames/*.jpg   1600x1200, shown normally
       hardware/viewer/hd/*.jpg       2400x1800, swapped in when zoomed
       hardware/viewer/stills/*.jpg
       hardware/viewer/data.json (+ data.js so the page also works opened from disk)
"""
import json, os, glob
from PIL import Image

HW = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
REN = os.path.join(HW, "renders", "helmet")
TURN = os.path.join(REN, "viewer_build_hd")
STILLS = os.path.join(REN, "viewer_build", "stills")
DST = os.path.join(HW, "viewer")
BG = (14, 16, 20)          # must match --stage-bg in index.html
BASE_W = 1600


def flat(src):
    im = Image.open(src).convert("RGBA")
    bg = Image.new("RGBA", im.size, BG + (255,))
    bg.alpha_composite(im)
    return bg.convert("RGB")


def save(im, path, q):
    im.save(path, "JPEG", quality=q, optimize=True, progressive=True)


for d in ("frames", "hd", "stills"):
    os.makedirs(os.path.join(DST, d), exist_ok=True)

n = 0
for f in sorted(glob.glob(os.path.join(TURN, "raw", "*.png"))):
    name = os.path.basename(f)[:-4] + ".jpg"
    hd, base = os.path.join(DST, "hd", name), os.path.join(DST, "frames", name)
    if os.path.exists(hd) and os.path.getmtime(hd) >= os.path.getmtime(f):
        continue
    im = flat(f)
    save(im, hd, 80)
    save(im.resize((BASE_W, BASE_W * 3 // 4), Image.LANCZOS), base, 84)
    n += 1
for f in sorted(glob.glob(os.path.join(STILLS, "*.png"))):
    save(flat(f), os.path.join(DST, "stills", os.path.basename(f)[:-4] + ".jpg"), 88)

hs = json.load(open(os.path.join(TURN, "hotspots.json")))
info = json.load(open(os.path.join(REN, "helmate_on_helmet_info.json")))
variants = sorted({os.path.basename(f).split("_e")[0] for f in glob.glob(os.path.join(DST, "frames", "*.jpg"))})
data = {
    "azStep": hs["az_step"], "els": hs["els"], "baseW": BASE_W, "hd": True,
    "frames": hs["frames"], "cableCm": info["cable_length_cm"], "variants": variants,
    "stills": sorted(os.path.basename(f)[:-4] for f in glob.glob(os.path.join(DST, "stills", "*.jpg"))),
}
js = json.dumps(data, separators=(",", ":"))
open(os.path.join(DST, "data.json"), "w", encoding="utf-8").write(js)
open(os.path.join(DST, "data.js"), "w", encoding="utf-8").write(
    "// generated by hardware/tools/build_viewer.py\nwindow.HELMATE_DATA = " + js + ";\n")

size = lambda d: sum(os.path.getsize(f) for f in glob.glob(os.path.join(DST, d, "*.jpg"))) / 1e6
print(f"converted {n} frames | frames {size('frames'):.1f} MB, hd {size('hd'):.1f} MB, stills {size('stills'):.1f} MB | variants {variants}")
